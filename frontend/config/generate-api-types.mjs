// Turns an OpenAPI spec exported by `just generate_api_types` into TypeScript types for the SPA.
//
// Usage: bun frontend/config/generate-api-types.mjs <spec.json> <out.d.ts>
//
// This uses openapi-typescript's Node API rather than its CLI so that file fields (`format: binary`, e.g. the avatar
// upload) are typed as `Blob` instead of `string`, which lets multipart bodies type-check without casts.
import { readFileSync, writeFileSync } from 'node:fs';
import openapiTS, { astToString } from 'openapi-typescript';
import ts from 'typescript';

const [specPath, outPath] = process.argv.slice(2);
if (!specPath || !outPath) {
  console.error('Usage: bun frontend/config/generate-api-types.mjs <spec.json> <out.d.ts>');
  process.exit(2);
}

const BLOB = ts.factory.createTypeReferenceNode(ts.factory.createIdentifier('Blob'));
const NULL = ts.factory.createLiteralTypeNode(ts.factory.createNull());

const ast = await openapiTS(JSON.parse(readFileSync(specPath, 'utf8')), {
  transform(schemaObject) {
    if (schemaObject.format === 'binary') {
      return schemaObject.nullable ? ts.factory.createUnionTypeNode([BLOB, NULL]) : BLOB;
    }
    return undefined;
  },
});

const header = `// Generated by \`just generate_api_types\`. Don't edit by hand; change the backend and regenerate.\n\n`;
writeFileSync(outPath, header + astToString(ast));
